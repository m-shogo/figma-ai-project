<?php
/**
 * REF-001 Reason — learning First Pass.
 *
 * Figma strategy: STRUCTURE_FIRST.
 * The current CMS baseline intentionally uses three fixed field sets. Figma's
 * repeated visual cards do not prove an editor add/remove/reorder requirement.
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

$intro = ref001_get_field(
	'reason_intro',
	'学生一人ひとりに寄り添う教育と、地域に根ざした実践的な学びで、将来につながる力を育みます。'
);

$defaults = array(
	1 => array(
		'title' => '少人数教育',
		'body'  => '一人ひとりに目が届く少人数教育。質問や相談もしやすい環境です。',
	),
	2 => array(
		'title' => '充実のキャリア支援',
		'body'  => 'キャリア支援と企業連携により、希望進路の実現をサポートします。',
	),
	3 => array(
		'title' => '地域連携・インターンシップ',
		'body'  => '地域企業・自治体との実践的な学びで、社会で活きる力を養います。',
	),
);

$cards = array();
foreach ( $defaults as $index => $fallback ) {
	$image_id = ref001_get_field( "reason_{$index}_image", 0 );
	$cards[]  = array(
		'image' => ref001_get_attachment_image(
			$image_id,
			'large',
			array(
				'class' => 'ref001-reason__image',
				'alt'   => '',
			)
		),
		'title' => ref001_get_field( "reason_{$index}_title", $fallback['title'] ),
		'body'  => ref001_get_field( "reason_{$index}_body", $fallback['body'] ),
		'field' => "reason_{$index}_image",
	);
}
?>
<section class="ref001-reason" aria-labelledby="ref001-reason-title" data-figma-pc="21378:7999" data-figma-sp="21376:4852">
	<header class="ref001-reason__header">
		<p class="ref001-reason__kicker"># REASON</p>
		<h2 id="ref001-reason-title" class="ref001-reason__title">
			<span class="ref001-reason__paren" aria-hidden="true">（</span>
			<span class="ref001-reason__title-text"><span>千葉経済大学が</span><strong>選ばれる理由</strong></span>
			<span class="ref001-reason__paren" aria-hidden="true">）</span>
		</h2>
		<p class="ref001-reason__intro"><?php echo esc_html( $intro ); ?></p>
	</header>

	<div class="ref001-reason__cards">
		<?php foreach ( $cards as $card ) : ?>
			<article class="ref001-reason__card">
				<div class="ref001-reason__media">
					<?php if ( $card['image'] ) : ?>
						<?php echo $card['image']; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- generated by wp_get_attachment_image(). ?>
					<?php else : ?>
						<div class="ref001-reason__missing-media" data-missing-acf="<?php echo esc_attr( $card['field'] ); ?>" aria-hidden="true"></div>
					<?php endif; ?>
				</div>

				<div class="ref001-reason__card-body">
					<h3 class="ref001-reason__card-title"><?php echo esc_html( $card['title'] ); ?></h3>
					<p class="ref001-reason__card-copy"><?php echo esc_html( $card['body'] ); ?></p>
				</div>
			</article>
		<?php endforeach; ?>
	</div>
</section>
