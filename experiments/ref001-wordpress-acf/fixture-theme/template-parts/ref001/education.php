<?php
/**
 * REF-001 Education — learning First Pass.
 *
 * Figma strategy: HYBRID.
 * Internal list structure is trustworthy, while the outer PC/SP stage
 * composition is visually verified rather than copied from raw coordinates.
 *
 * CMS contract: exactly four ordered stages. The stage number/semantic label
 * is code-owned; editors can change content but cannot add/remove/reorder the
 * 01→04 learning progression in this baseline.
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

$intro = ref001_get_field(
	'education_intro',
	'千葉経済大学では、経済や経営を学びながら、世の中の仕組みを知り、自分の興味や可能性を見つけていきます。'
);

$stage_contract = array(
	1 => array(
		'number' => '01', 'label' => 'スタート', 'title' => '大学1年生の自分',
		'bullets' => array( '将来がまだ見えない', '学科選択制度で基礎を学ぶ', '７つのコースで目標を明確に', '資格取得支援でスキルを発見' ),
	),
	2 => array(
		'number' => '02', 'label' => '学ぶ', 'title' => '世の中の仕組みを知る',
		'bullets' => array( 'ヒット商品の裏側', 'トクするお金のルール', 'AIで仕事はどうなる' ),
	),
	3 => array(
		'number' => '03', 'label' => '出会う', 'title' => '先生と一緒に考える',
		'bullets' => array( '教職員との距離が近い', '悩みを相談しやすい', '個人に合わせた進路のサポート' ),
	),
	4 => array(
		'number' => '04', 'label' => 'ゴール', 'title' => '望んだ将来を実現させる',
		'bullets' => array( '４年間の学びを進路につなげる', '経験を社会で発揮する', '自分らしい未来を見つける' ),
	),
);

$stages = array();
foreach ( $stage_contract as $index => $contract ) {
	$bullets = array();
	foreach ( $contract['bullets'] as $bullet_index => $fallback ) {
		$bullets[] = ref001_get_field( 'education_' . $index . '_bullet_' . ( $bullet_index + 1 ), $fallback );
	}

	$image_id = ref001_get_field( 'education_' . $index . '_image', 0 );
	$stages[] = array(
		'number' => $contract['number'],
		'label' => $contract['label'],
		'title' => ref001_get_field( 'education_' . $index . '_title', $contract['title'] ),
		'bullets' => $bullets,
		'image' => ref001_get_attachment_image(
			$image_id,
			'large',
			array( 'class' => 'ref001-education__image', 'alt' => '' )
		),
		'field' => 'education_' . $index . '_image',
	);
}
?>
<section class="ref001-education" aria-labelledby="ref001-education-title" data-figma-pc="21378:7868" data-figma-sp="21376:4720">
	<header class="ref001-education__header">
		<p class="ref001-education__kicker"># EDUCATION</p>
		<h2 id="ref001-education-title" class="ref001-education__title">４年間の学び</h2>
		<div class="ref001-education__lead-rule" aria-hidden="true"></div>
		<p class="ref001-education__subheading">将来、これから探しても大丈夫</p>
		<p class="ref001-education__intro"><?php echo esc_html( $intro ); ?></p>
	</header>

	<ol class="ref001-education__stages">
		<?php foreach ( $stages as $stage_index => $stage ) : ?>
			<li class="ref001-education__stage">
				<article class="ref001-education__card">
					<div class="ref001-education__badge">
						<span class="ref001-education__number"><?php echo esc_html( $stage['number'] ); ?></span>
						<span class="ref001-education__slash" aria-hidden="true">/</span>
						<span class="ref001-education__label"><?php echo esc_html( $stage['label'] ); ?></span>
					</div>

					<div class="ref001-education__summary">
						<div class="ref001-education__media">
							<?php if ( $stage['image'] ) : ?>
								<?php echo $stage['image']; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- generated by wp_get_attachment_image(). ?>
							<?php else : ?>
								<div class="ref001-education__missing-media" data-missing-acf="<?php echo esc_attr( $stage['field'] ); ?>" aria-hidden="true"></div>
							<?php endif; ?>
						</div>
						<h3 class="ref001-education__card-title"><?php echo esc_html( $stage['title'] ); ?></h3>
					</div>

					<ul class="ref001-education__bullets">
						<?php foreach ( $stage['bullets'] as $bullet ) : ?>
							<?php if ( '' !== trim( (string) $bullet ) ) : ?>
								<li><?php echo esc_html( $bullet ); ?></li>
							<?php endif; ?>
						<?php endforeach; ?>
					</ul>
				</article>

				<?php if ( $stage_index < count( $stages ) - 1 ) : ?>
					<span class="ref001-education__connector" aria-hidden="true">⌄</span>
				<?php endif; ?>
			</li>
		<?php endforeach; ?>
	</ol>
</section>
